#!/usr/bin/env node
/* Regenerates data/evo-pages.js from a local copy of the NCDOT Certified
 * Escort Vehicle Operator Handbook PDF (May 2017 revision).
 *
 * Like the CDL manual, the handbook prints chapter-relative page labels
 * ("3-5") in its footers, and that is what the EVO questions cite; a PDF
 * viewer's #page= fragment wants the physical page index, so this walks the
 * PDF and maps one to the other. The two appendices are labelled "Appendix A"
 * and "Appendix B" rather than numbered, so they map as "A" and "B", first
 * page of each.
 *
 * Usage: node tools/gen-evo-pages.js [path-to-evo-handbook.pdf]
 * Needs pdftotext (poppler-utils) on PATH. The PDF is not in the repo; grab
 * it from the NCDOT link in data/exam-config.js first. */
const { execFileSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const pdf = process.argv[2] || path.join(__dirname, '..', 'evo-handbook.pdf');
if (!fs.existsSync(pdf)) {
  console.error(`${pdf} not found. Download the EVO handbook PDF first, or pass its path.`);
  process.exit(1);
}

const text = execFileSync('pdftotext', ['-layout', pdf, '-'], { maxBuffer: 64 * 1024 * 1024 }).toString();
const pages = text.split('\f');
const map = {};
for (let i = 0; i < pages.length; i++) {
  for (const line of pages[i].split('\n').slice(-8)) {
    const m = /(?:Page (\d+-\d+)|Appendix ([A-Z]))\s*$/.exec(line.trimEnd());
    const label = m && (m[1] || m[2]);
    if (label && !(label in map)) map[label] = i + 1;
  }
}

const labels = Object.keys(map).sort((a, b) => map[a] - map[b]);
const body = labels.map(l => `  '${l}': ${map[l]},`).join('\n');
const out = `/* Generated by tools/gen-evo-pages.js. Do not edit by hand.
   Maps the EVO handbook's printed page labels ("3-5", appendices "A"/"B") to
   physical page numbers in the NCDOT PDF, so a citation can deep link with
   #page=. Regenerate whenever NCDOT publishes a new revision. */
const EVO_PAGES = {
${body}
};
`;
const dest = path.join(__dirname, '..', 'data', 'evo-pages.js');
fs.writeFileSync(dest, out);
console.log(`wrote ${labels.length} page labels to ${path.relative(process.cwd(), dest)}`);
